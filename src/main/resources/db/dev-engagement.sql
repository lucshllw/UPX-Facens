CREATE TABLE IF NOT EXISTS favorites (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 item_id BIGINT NOT NULL REFERENCES items(id) ON DELETE CASCADE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,item_id)
);
CREATE TABLE IF NOT EXISTS reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id BIGINT NOT NULL REFERENCES items(id) ON DELETE CASCADE,
 requester_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 owner_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 note VARCHAR(500),
 reserved_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 decided_at TIMESTAMP WITH TIME ZONE,
 CHECK(requester_id <> owner_id)
);
